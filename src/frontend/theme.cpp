namespace {

ImFont *addEmbedded(ImFontAtlas &atlas, const unsigned char *data, std::size_t size, const char *name) {
	ImFontConfig cfg;
	cfg.FontDataOwnedByAtlas = false; // static data, never freed
	std::snprintf(cfg.Name, sizeof(cfg.Name), "%s", name);
	return atlas.AddFontFromMemoryTTF(const_cast<unsigned char *>(data), int(size), 16.0f, &cfg);
}

} // namespace

UiFonts addUiFonts(ImFontAtlas &atlas) {
	UiFonts f;
	f.regular = addEmbedded(atlas, embedded::nunitoRegular, embedded::nunitoRegularSize, "Nunito");
	f.bold = addEmbedded(atlas, embedded::nunitoBold, embedded::nunitoBoldSize, "Nunito Bold");
	f.mono = atlas.AddFontDefaultVector();
	if (!f.regular) // (cannot happen with the compiled-in data)
		f.regular = f.mono;
	if (!f.bold)
		f.bold = f.regular;
	return f;
}

